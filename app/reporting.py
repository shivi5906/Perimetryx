"""Executive and technical security audit report generator (Markdown and HTML)."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .store import db, load, rows


def generate_audit_data(scan_id: int) -> dict[str, Any]:
    with db() as conn:
        scan_row = conn.execute(
            """SELECT s.*, d.root_domain, d.scope_json
               FROM scans s JOIN domains d ON d.id = s.domain_id
               WHERE s.id = ?""",
            (scan_id,),
        ).fetchone()
        if not scan_row:
            raise ValueError(f"Scan {scan_id} not found")

        domain = scan_row["root_domain"]
        scope = load(scan_row["scope_json"])
        stats = load(scan_row["stats_json"])

        assets = rows(conn.execute(
            """SELECT a.id, a.hostname, a.environment, a.source,
                      r.total as score, r.band, r.breakdown_json,
                      o.status_code, o.title, o.headers_json, o.cname, o.response_time_ms
               FROM scan_assets sa
               JOIN assets a ON a.id = sa.asset_id
               LEFT JOIN risk_scores r ON r.asset_id = a.id AND r.scan_id = sa.scan_id
               LEFT JOIN observations o ON o.asset_id = a.id AND o.scan_id = sa.scan_id
               WHERE sa.scan_id = ?
               ORDER BY r.total DESC""",
            (scan_id,),
        ))

        findings = rows(conn.execute(
            """SELECT f.*, a.hostname
               FROM findings f
               JOIN assets a ON a.id = f.asset_id
               WHERE f.scan_id = ?
               ORDER BY f.cvss_score DESC""",
            (scan_id,),
        ))

        technologies = rows(conn.execute(
            """SELECT t.*, a.hostname
               FROM technologies t
               JOIN assets a ON a.id = t.asset_id
               WHERE t.scan_id = ?""",
            (scan_id,),
        ))

        certificates = rows(conn.execute(
            """SELECT c.*, a.hostname
               FROM certificates c
               JOIN assets a ON a.id = c.asset_id
               WHERE c.scan_id = ?""",
            (scan_id,),
        ))

    # Parse JSON fields
    for a in assets:
        a["breakdown"] = load(a.pop("breakdown_json", "{}"))
        a["headers"] = load(a.pop("headers_json", "{}"))

    for f in findings:
        f["evidence"] = load(f.pop("evidence_json", "{}"))

    for c in certificates:
        c["sans"] = load(c.pop("sans_json", "[]"))

    # Severity distribution
    sev_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
    for f in findings:
        sev = (f.get("severity") or "medium").lower()
        sev_counts[sev] = sev_counts.get(sev, 0) + 1

    return {
        "scan_id": scan_id,
        "domain": domain,
        "started_at": scan_row["started_at"],
        "completed_at": scan_row["completed_at"],
        "dry_run": bool(scan_row["dry_run"]),
        "scope": scope,
        "stats": stats,
        "assets": assets,
        "findings": findings,
        "technologies": technologies,
        "certificates": certificates,
        "severity_counts": sev_counts,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
    }


def generate_markdown_report(scan_id: int) -> str:
    data = generate_audit_data(scan_id)
    lines = [
        f"# Attack Surface Security Assessment Report: {data['domain']}",
        f"*Generated by Perimetryx v2.0 on {data['generated_at']}*",
        "",
        "---",
        "",
        "## 1. Executive Summary",
        f"- **Target Root Domain**: `{data['domain']}`",
        f"- **Scan Mode**: `{'Dry Run (Simulation)' if data['dry_run'] else 'Authorized Live Assessment'}`",
        f"- **Discovered Assets**: `{len(data['assets'])}`",
        f"- **Total Security Findings**: `{len(data['findings'])}`",
        f"- **Severity Breakdown**: **{data['severity_counts']['critical']}** Critical | **{data['severity_counts']['high']}** High | **{data['severity_counts']['medium']}** Medium | **{data['severity_counts']['low']}** Low",
        "",
        "| Hostname | Environment | Status | Risk Score | Severity Band |",
        "|---|---|---|---|---|",
    ]

    for a in data["assets"]:
        lines.append(
            f"| `{a['hostname']}` | `{a['environment']}` | `{a['status_code'] or 'Unreachable'}` | `{a['score'] or 0}/100` | `{str(a['band']).upper()}` |"
        )

    lines.extend([
        "",
        "## 2. Security Findings & Threat Intelligence",
        "",
    ])

    if not data["findings"]:
        lines.append("*No security posture anomalies or vulnerabilities detected in this scan.*")
    else:
        for idx, f in enumerate(data["findings"], 1):
            lines.extend([
                f"### {idx}. [{f['severity'].upper()}] {f['description']} (`{f['rule_id']}`)",
                f"- **Affected Asset**: `{f['hostname']}`",
                f"- **Classification**: `{f['classification']}`",
                f"- **CVSS v3.1 Base Score**: `{f['cvss_score']}`",
                f"- **MITRE ATT&CK**: `{f['mitre_technique'] or 'N/A'}` | **CWE ID**: `{f['cwe_id'] or 'N/A'}`",
                "",
                "```json",
                json.dumps(f["evidence"], indent=2),
                "```",
                "",
            ])

    lines.extend([
        "## 3. Technology Inventory",
        "",
        "| Hostname | Technology | Category | Version |",
        "|---|---|---|---|",
    ])
    for t in data["technologies"]:
        lines.append(f"| `{t['hostname']}` | **{t['name']}** | {t['category']} | {t['version'] or 'N/A'} |")

    lines.extend([
        "",
        "## 4. Scope & Compliance Verification",
        f"- **Authorization Basis**: `{data['scope'].get('authorization_basis', 'N/A')}`",
        f"- **Allowed Patterns**: `{', '.join(data['scope'].get('allowed_domains', []))}`",
        f"- **Excluded Patterns**: `{', '.join(data['scope'].get('excluded', [])) or 'None'}`",
        "- **Assessment Boundary**: External passive reconnaissance and safe, non-destructive HTTP/DNS observation only.",
        "",
        "---",
        "*Perimetryx Attack Surface Intelligence — Confidential Security Audit Document*",
    ])

    return "\n".join(lines)


